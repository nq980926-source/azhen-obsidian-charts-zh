import esbuild from "esbuild";
import fs from "node:fs/promises";
import path from "node:path";
import process from "process";
import { compile, preprocess } from "svelte/compiler";
import autoPreprocess from "svelte-preprocess";

const banner = 
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
Simplified Chinese version based on phibr0/obsidian-charts 3.9.0.
Source: https://github.com/nq980926-source/azhen-obsidian-charts-zh
Upstream: https://github.com/phibr0/obsidian-charts
*/
`;

const localSveltePlugin = {
    name: "local-svelte",
    setup(build) {
        build.onLoad({ filter: /\.svelte$/ }, async (args) => {
            const originalSource = await fs.readFile(args.path, "utf8");
            const preprocessed = await preprocess(originalSource, autoPreprocess(), {
                filename: args.path,
            });
            const compiled = compile(preprocessed.code, {
                filename: args.path,
                css: true,
                dev: false,
                ...(preprocessed.map ? { sourcemap: preprocessed.map } : {}),
            });
            return {
                contents: compiled.js.code,
                loader: "js",
                resolveDir: path.dirname(args.path),
                watchFiles: [args.path],
            };
        });
    },
};

esbuild.build({
    banner: {
        js: banner,
    },
    entryPoints: ['src/main.ts'],
    bundle: true,
    external: ['obsidian', 'moment'],
    format: 'cjs',
    charset: 'utf8',
    minify: true,
    watch: false,
    logLevel: "info",
    treeShaking: true,
    plugins: [localSveltePlugin],
    outfile: 'main.js',
}).catch(() => process.exit(1));
